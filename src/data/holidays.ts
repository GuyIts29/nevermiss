export function getHolidayById(id: string): Holiday | undefined {
  return HOLIDAYS.find(h => h.id === id)
}

export function getHolidaysByReligion(religion: string): Holiday[] {
  return HOLIDAYS.filter(h => h.religion === religion)
}

export function getHolidaysByDateRange(start: Date, end: Date): Holiday[] {
  return HOLIDAYS.filter(h => {
    const d = new Date(h.date)
    return d >= start && d <= end
  })
}

export function getUpcomingHolidays(days: number = 30): Holiday[] {
  const now = new Date()
  const future = new Date(now.getTime() + days * 24 * 60 * 60 * 1000)
  return getHolidaysByDateRange(now, future).sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  )
}

export function getHolidaysForMonth(year: number, month: number): Holiday[] {
  return HOLIDAYS.filter(h => {
    const d = new Date(h.date)
    return d.getFullYear() === year && d.getMonth() === month
  })
}

