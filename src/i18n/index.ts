export type TranslationKey = keyof typeof translations.en

export function t(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const map = translations[lang] as Record<string, string>
  let text = map[key] ?? (translations.en as Record<string, string>)[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v))
    })
  }
  return text
}

const RTL_LANG_CODES = new Set(['he', 'ar', 'fa', 'ur', 'yi', 'dv'])
export function dir(langCode: string): 'rtl' | 'ltr' {
  return RTL_LANG_CODES.has(langCode.toLowerCase().split('-')[0]) ? 'rtl' : 'ltr'
}
